using UnityEngine;

/// <summary>
/// Один символ, который может выпасть в ячейке слот-машины.
/// Это ScriptableObject — создаёшь ассет через правый клик -> Create -> SlotMachine -> Symbol
/// для каждого символа отдельно (меч, щит, молния, мусор, череп и т.д.)
/// </summary>
[CreateAssetMenu(fileName = "NewSlotSymbol", menuName = "SlotMachine/Symbol")]
public class SlotSymbol : ScriptableObject
{
    [Header("Идентификация")]
    // Уникальный ID символа. ВАЖНО: у ВСЕХ "мусорных" ячеек должен быть ОДИН И ТОТ ЖЕ id
    // (например -1), и у ВСЕХ "черепов" тоже один и тот же id (например -2).
    // Это то, что позволяет паттерну из мусора/черепов "совпасть" точно так же,
    // как паттерну из оружия — сравнение идёт просто по числу.
    // Обычные предметы — уникальные положительные id (0, 1, 2, 3...).
    public int symbolId;

    [Header("Визуал")]
    // Спрайт, который показывается в ячейке на барабане.
    // Не обязан совпадать с иконкой предмета в инвентаре — это отдельная "слотовая" картинка.
    public Sprite icon;

    [Header("Связь с предметом")]
    // Какой предмет выдаётся, если этот символ выиграл.
    // Для мусора и черепа оставляй пустым (null) — они не выдают предмет.
    public ItemSO linkedItem;

    [Header("Вероятность")]
    // Вес символа при случайном заполнении сетки. Чем больше число — тем чаще выпадает.
    // Пример: мусор = 100, обычное оружие = 20, редкое оружие = 5.
    public int weight = 10;

    [Header("Флаги поведения")]
    // true = это "пустой" мусорный символ.
    public bool isJunk = false;

    // true = это символ черепа — опасная ветка (урон/смерть при совпадении паттерна).
    public bool isSkull = false;
}
