/// <summary>
/// Реализуй этот интерфейс на своём существующем PlayerController, чтобы слот-машина
/// могла с ним работать — списывать валюту за спин и применять урон/смерть от черепов.
/// Специально минимальный и не завязан на конкретный класс игрока — просто добавь
/// ": ISlotSpinner" к объявлению своего класса и реализуй три метода ниже.
/// </summary>
public interface ISlotSpinner
{
    // Пытается списать стоимость спина. Верни false, если не хватает валюты —
    // тогда SlotMachineController не станет крутить и ничего не спишет.
    bool TrySpendCurrency(int amount);

    // Урон от паттерна черепа (обычный, не джекпот).
    void ApplyDamage(float amount);

    // Мгновенная смерть/вайп — вызывается при джекпоте черепами.
    void Kill();
}
